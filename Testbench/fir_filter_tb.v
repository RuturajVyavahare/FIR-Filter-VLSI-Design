
`timescale 1ns/1ps

module fir_filter_tb;

    // Testbench signals
    reg clk;
    reg rst;
    reg valid_in;
    reg signed [15:0] x_in;

    wire signed [15:0] y_out;
    wire valid_out;

    integer i;
    integer sample_index;
    integer expected_value;
    integer errors;
    integer log_file;

    reg signed [15:0] test_coeff [0:31];
    reg signed [31:0] expected_product;

    // Device under test
    fir_filter uut (
        .clk       (clk),
        .rst       (rst),
        .x_in      (x_in),
        .valid_in  (valid_in),
        .y_out     (y_out),
        .valid_out (valid_out)
    );

    // 100 MHz clock
    initial clk = 1'b0;
    always #5 clk = ~clk;

    // Q1.15 FIR coefficients generated by MATLAB
    initial begin
        test_coeff[0]  = 16'sd31;
        test_coeff[1]  = -16'sd15;
        test_coeff[2]  = -16'sd80;
        test_coeff[3]  = -16'sd127;
        test_coeff[4]  = -16'sd71;
        test_coeff[5]  = 16'sd139;
        test_coeff[6]  = 16'sd407;
        test_coeff[7]  = 16'sd470;
        test_coeff[8]  = 16'sd77;
        test_coeff[9]  = -16'sd720;
        test_coeff[10] = -16'sd1409;
        test_coeff[11] = -16'sd1209;
        test_coeff[12] = 16'sd432;
        test_coeff[13] = 16'sd3341;
        test_coeff[14] = 16'sd6520;
        test_coeff[15] = 16'sd8597;
        test_coeff[16] = 16'sd8597;
        test_coeff[17] = 16'sd6520;
        test_coeff[18] = 16'sd3341;
        test_coeff[19] = 16'sd432;
        test_coeff[20] = -16'sd1209;
        test_coeff[21] = -16'sd1409;
        test_coeff[22] = -16'sd720;
        test_coeff[23] = 16'sd77;
        test_coeff[24] = 16'sd470;
        test_coeff[25] = 16'sd407;
        test_coeff[26] = 16'sd139;
        test_coeff[27] = -16'sd71;
        test_coeff[28] = -16'sd127;
        test_coeff[29] = -16'sd80;
        test_coeff[30] = -16'sd15;
        test_coeff[31] = 16'sd31;
    end

    // Apply reset and impulse input
    initial begin
        log_file = 0;
        errors = 0;
        sample_index = 0;
        i = 0;
        rst = 1'b1;
        valid_in = 1'b0;
        x_in = 16'sd0;

        // Open CSV results file
        log_file = $fopen("fir_rtl_results.csv", "w");

        if (log_file == 0) begin
            $display("ERROR: Could not open results log.");
            $finish;
        end

        $fdisplay(log_file,
                  "sample_index,input_sample,rtl_output,expected_output,status");

        // Hold reset for two clock cycles
        repeat (2) @(negedge clk);
        rst = 1'b0;

        // Send one impulse followed by 31 zero samples
        for (i = 0; i < 32; i = i + 1) begin
            @(negedge clk);
            valid_in = 1'b1;

            if (i == 0)
                x_in = 16'sd1000;
            else
                x_in = 16'sd0;
        end

        // Stop accepting input samples
        @(negedge clk);
        valid_in = 1'b0;
        x_in = 16'sd0;

        // Allow the final registered output to be checked
        repeat (3) @(negedge clk);

        $fclose(log_file);

        $display("----------------------------------------");
        $display("FIR FILTER SIMULATION SUMMARY");
        $display("Total samples checked: %0d", sample_index);
        $display("Total mismatches: %0d", errors);

        if ((errors == 0) && (sample_index == 32))
            $display("PASS: All 32 impulse-response samples matched.");
        else
            $display("FAIL: Check the RTL, timing, and testbench results.");

        $display("----------------------------------------");
        $display("Simulation test completed.");

        $finish;
    end

    // Compare output after registered signals have updated
    always @(posedge clk) begin
        #1;

        if (!rst && valid_out) begin
            // Expected fixed-point output:
            // signed coefficient * input, scaled by 2^15
            expected_product = test_coeff[sample_index] * 1000;
            expected_value = expected_product >>> 15;

            if (y_out !== expected_value) begin
                errors = errors + 1;

                $display("FAIL sample=%0d RTL=%0d expected=%0d",
                         sample_index, y_out, expected_value);

                $fdisplay(log_file, "%0d,1000,%0d,%0d,FAIL",
                          sample_index, y_out, expected_value);
            end
            else begin
                $display("PASS sample=%0d RTL=%0d expected=%0d",
                         sample_index, y_out, expected_value);

                $fdisplay(log_file, "%0d,1000,%0d,%0d,PASS",
                          sample_index, y_out, expected_value);
            end

            sample_index = sample_index + 1;
        end
    end

endmodule
